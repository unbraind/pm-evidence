import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test, type TestContext } from 'node:test';
import * as sdk from '../dist/index.js';
import { cite, review } from '../index.ts';
import { parseCitation } from '../src/citation-schema.ts';
import { digest } from '../src/core.ts';
import { Store } from '../src/store.ts';
import { tracker } from './helpers.ts';

test('custom retries preserve old generated IDs and retained-byte upgrades', async t => {
  const fixture = JSON.parse(await readFile(new URL('./fixtures/custom-provider-legacy-citation.json', import.meta.url), 'utf8')) as { baseline: string; unretained: unknown; retained: unknown };
  assert.equal(fixture.baseline, '049dc82');
  for (const api of [{ cite, review }, sdk]) for (const original of [fixture.unretained, fixture.retained]) {
    const f = await tracker(t); const legacy = parseCitation(original, f.item); const store = new Store(f.options);
    assert.equal(legacy.descriptor.source, './sample.txt');
    let text = 'sample.txt:old';
    const options = { ...f.options, provider: 'opaque', selector: { kind: 'lines', start: 1, end: 1 } as const, adapters: [{ provider: 'opaque', read: async () => ({ text, revision: digest(text) }) }] };
    await store.mutate(f.item, value => { value.citations.push(legacy); return { value: true, observation: 'Install citation generated by released source' }; });
    await api.review(f.item, { ...f.options, citation: legacy.id, disposition: 'still-valid', reason: 'Preserve existing observations' });
    const before = (await store.get(f.item)).value.citations[0];
    assert.equal((await api.cite(f.item, '././sample.txt', options)).citation, legacy.id);
    assert.deepEqual((await store.get(f.item)).value.citations, [before]);
    for (const operand of ['././sample.txt', 'sample.txt', './sample.txt']) {
      const receipt = await api.cite(f.item, operand, { ...options, retain: true });
      assert.equal(receipt.citation, legacy.id);
      assert.deepEqual((await store.get(f.item)).value.citations, [{ ...before, retained: parseCitation(fixture.retained).retained }]);
    }
    text += ':changed';
    const changed = await api.cite(f.item, '././sample.txt', options);
    assert.notEqual(changed.citation, legacy.id); assert.equal((await store.get(f.item)).value.citations.length, 2);
  }
  const f = await tracker(t); const legacy = parseCitation(fixture.unretained, f.item); legacy.id = 'ev-' + '0'.repeat(24);
  await new Store(f.options).mutate(f.item, value => { value.citations.push(legacy); return { value: true, observation: 'Foreign citation identity control' }; });
  const text = 'sample.txt:old';
  const fresh = await cite(f.item, 'sample.txt', { ...f.options, provider: 'opaque', selector: legacy.descriptor.selector, adapters: [{ provider: 'opaque', read: async () => ({ text, revision: digest(text) }) }] });
  assert.notEqual(fresh.citation, legacy.id); assert.equal((await new Store(f.options).get(f.item)).value.citations.length, 2);
});


/** Share genuine legacy producer data and bounded custom reads across retry controls. */
async function legacyTracker(t: TestContext) {
  const fixture = JSON.parse(await readFile(new URL('./fixtures/custom-provider-legacy-citation.json', import.meta.url), 'utf8')) as { unretained: unknown };
  const f = await tracker(t); const legacy = parseCitation(fixture.unretained, f.item);
  const text = 'sample.txt:old';
  const options = { ...f.options, provider: 'opaque', selector: legacy.descriptor.selector, adapters: [{ provider: 'opaque', read: async () => ({ text, revision: digest(text) }) }] };
  return { ...f, legacy, store: new Store(f.options), options };
}

test('custom re-anchor retries reuse legacy replacement IDs and observations', async t => {
  for (const api of [{ cite, review }, sdk]) {
    const f = await legacyTracker(t); const { legacy, store, options } = f;
    await store.mutate(f.item, value => { value.citations.push(legacy); return { value: true, observation: 'Legacy replacement candidate' }; });
    const request = { ...options, citation: legacy.id, disposition: 're-anchored' as const, reason: 'Refresh the same passage' };
    const first = await api.review(f.item, request);
    assert.equal(first.replacement, legacy.id);
    const before = (await store.get(f.item)).value;
    assert.equal(before.citations.length, 1); assert.equal(before.citations[0].reviews.length, 1);
    assert.deepEqual(await api.review(f.item, request), first);
    assert.deepEqual((await store.get(f.item)).value, before);
  }
});


test('custom exact IDs take precedence over earlier canonical aliases', async t => {
  for (const api of [{ cite, review }, sdk]) {
    const f = await legacyTracker(t); const { legacy, store, options } = f;
    const canonical = await api.cite(f.item, 'sample.txt', options);
    const reason = 'Previously recorded canonical replacement';
    const observation = { id: `review-${digest(JSON.stringify([f.item, legacy.id, f.options.author, 're-anchored', reason, canonical.citation])).slice(0, 24)}`, author: f.options.author, at: legacy.provenance.at, disposition: 're-anchored' as const, reason, replacement: canonical.citation };
    legacy.reviews.push(observation);
    await store.mutate(f.item, value => { value.citations.unshift(legacy); return { value: true, observation: 'Preserve pre-existing alias and canonical citations' }; });
    const before = (await store.get(f.item)).value;
    assert.equal((await api.cite(f.item, '././sample.txt', options)).citation, canonical.citation);
    const receipt = await api.review(f.item, { ...options, citation: legacy.id, disposition: 're-anchored', reason });
    assert.equal(receipt.replacement, canonical.citation); assert.equal(receipt.observation, observation.id);
    assert.deepEqual((await store.get(f.item)).value, before);
  }
});
